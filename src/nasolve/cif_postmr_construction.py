"""Fresh, MTZ-free controls for the ordinary PostMR construction boundary.

These controls exercise Coot and the same construction function used by ordinary
PostMR. They do not simulate an MR result, call ReadySet, or qualify native
restraints or refinement. Source dictionaries are copied exactly, never repaired
or generated by this module.
"""
from __future__ import annotations

from dataclasses import asdict
from hashlib import sha256
import json
from math import dist
from pathlib import Path
from typing import Mapping

from .cif_construction_provenance import _pdb_inventory
from .cif_stereochemistry_audit import _graph, _values
from .postmr import MutationAction
from .synthetic_dna import prepare_free_five_prime_model

POLICY_ID = "cif-postmr-construction-controls-v1"
ORDINARY_POSTMR_CONSTRUCTION_CONTROLS = (
    {"site": "A:6", "parent": "DG", "component": "DP"},
    {"site": "A:9", "parent": "DT", "component": "PDU"},
    {"site": "A:7", "parent": "DC", "component": "5PC"},
)
FRAGMENT_DISTANCE_TOLERANCE = .002  # Serialized PDB coordinate rounding, Angstrom.


def _json(path: Path, value: dict) -> None:
    with path.open("x") as handle:
        json.dump(value, handle, indent=2, sort_keys=True, allow_nan=False)
        handle.write("\n")


def _reference(path: Path, root: Path) -> dict:
    path = Path(path)
    if path.is_symlink() or not path.resolve().is_relative_to(root.resolve()):
        raise ValueError("Construction evidence must remain inside its owned output")
    data = path.read_bytes()
    return {"anchor": "construction_directory", "path": path.relative_to(root).as_posix(),
            "sha256": sha256(data).hexdigest(), "size": len(data)}


def _preserved(paths: Mapping[str, Path], snapshots: Mapping[str, bytes]) -> bool:
    try:
        return all(path.read_bytes() == snapshots[name] for name, path in paths.items())
    except OSError:
        return False


def _canonical(name: str) -> str:
    return {"O1P": "OP1", "O2P": "OP2", "O3P": "OP3"}.get(name, name)


def _site(key: tuple) -> str:
    return key[0] + ":" + key[1]


def _atoms(inventory: dict, site: str) -> dict:
    result = {}
    for key, atom in inventory.items():
        if _site(key) != site:
            continue
        name = _canonical(key[-1])
        if key[2] or key[3] or name in result:
            raise ValueError("Ambiguous selected construction atom identity")
        result[name] = atom
    if not result:
        raise ValueError("Selected construction site absent: " + site)
    return result


def _records(path: Path) -> tuple[dict, list]:
    atoms = {}
    other = []
    for line in Path(path).read_text().splitlines(keepends=True):
        if line[:6] in {"ATOM  ", "HETATM"}:
            key = (line[21].strip() or "_", line[22:26].strip(), line[26].strip(),
                   line[16].strip(), line[12:16].strip())
            if key in atoms:
                raise ValueError("Duplicate construction record identity")
            atoms[key] = line
        else:
            other.append(line)
    return atoms, other


def _volume(points: list) -> float:
    center, first, second, anchor = points
    x, y, z = [[p[i] - center[i] for i in range(3)] for p in (first, second, anchor)]
    return (x[0] * (y[1]*z[2] - y[2]*z[1])
            - x[1] * (y[0]*z[2] - y[2]*z[0])
            + x[2] * (y[0]*z[1] - y[1]*z[0]))


def audit_postmr_construction(initial_model: Path, raw_model: Path, final_model: Path,
                              actions: tuple[MutationAction, ...],
                              dictionary_paths: Mapping[str, Path],
                              parent_models: Mapping[str, Path],
                              coordinate_restoration: Mapping[str, dict]) -> dict:
    """Independently test composition, frozen scaffold and raw fragment geometry.

    Unsupported graph contexts may keep the entire raw site. That fallback is
    tested byte for byte and is reported separately from successful transport.
    A completion message from Coot or a restoration receipt alone cannot pass
    this audit.
    """
    from .postmr_restoration import source_graph_fragment

    selected = {action.site for action in actions}
    if len(selected) != len(actions) or not selected:
        raise ValueError("Require unique explicit construction actions")
    initial, raw, final = map(_pdb_inventory, (initial_model, raw_model, final_model))
    raw_lines, raw_other = _records(raw_model)
    final_lines, final_other = _records(final_model)
    if raw.keys() != final.keys():
        raise ValueError("Construction restoration changed raw atom composition")
    if any(raw[k]["element"] != final[k]["element"] or raw[k]["code"] != final[k]["code"] for k in raw):
        raise ValueError("Construction restoration changed component or element identity")
    if raw_other != final_other:
        raise ValueError("Construction restoration changed non-coordinate records")
    for key in raw_lines:
        if _site(key) not in selected and raw_lines[key] != final_lines[key]:
            raise ValueError("Construction restoration changed an unselected record")
        if raw_lines[key][:30] + raw_lines[key][54:] != final_lines[key][:30] + final_lines[key][54:]:
            raise ValueError("Construction restoration changed atom metadata")
    initial_other = {k: v for k, v in initial.items() if _site(k) not in selected}
    raw_unselected = {k: v for k, v in raw.items() if _site(k) not in selected}
    if initial_other != raw_unselected:
        raise ValueError("Coot construction changed unselected coordinates or composition")

    results = []
    for action in actions:
        original = _atoms(initial, action.site)
        before, after = _atoms(raw, action.site), _atoms(final, action.site)
        if any(a["code"] != action.before for a in original.values()):
            raise ValueError("Fresh canonical parent identity differs at " + action.site)
        if any(a["code"] != action.after for a in before.values()):
            raise ValueError("Coot did not construct the requested component at " + action.site)
        values = _values(dictionary_paths[action.after], action.after)
        elements = _graph(values)[0]
        heavy = {_canonical(n): e for n, e in elements.items() if e not in {"H", "D"}}
        if any(name not in heavy or row["element"] != heavy[name] for name, row in before.items()):
            raise ValueError("Constructed atoms differ from the declared dictionary graph")
        graph = source_graph_fragment(dictionary_paths[action.after], action.after)
        fragment = graph["fragment_atoms"]
        scaffold = graph["scaffold_atoms"]
        if not set(fragment) <= before.keys():
            raise ValueError("Fresh constructed component is missing a declared base atom")
        if not (set(scaffold) & original.keys()) <= before.keys():
            raise ValueError("Fresh constructed component is missing a canonical scaffold atom")
        report = coordinate_restoration.get(action.site, {})
        status = report.get("status")
        if status == "RAW_SITE_RETAINED":
            if any(raw_lines[k] != final_lines[k] for k in raw_lines if _site(k) == action.site):
                raise ValueError("Raw fallback did not preserve the whole selected site")
            if not report.get("notes") or not report.get("reason"):
                raise ValueError("Raw fallback lacks an explicit reason and solution note")
            results.append({"site": action.site, "component": action.after, "status": status,
                            "raw_site_preserved": True, "notes": report["notes"],
                            "reason": report["reason"], "fragment_transport_tested": False})
            continue
        if status != "GRAPH_FRAGMENT_RESTORED":
            raise ValueError("Missing ordinary graph restoration outcome at " + action.site)
        # Every declared base atom must be present. Terminal phosphate atoms may
        # be absent in Coot's polymer context; record their exact inventory below.
        if not set(fragment) <= before.keys():
            raise ValueError("Fresh constructed component is missing a declared base atom")
        parent = _atoms(_pdb_inventory(parent_models[action.site]), action.site)
        if any(row["code"] != action.parent_code for row in parent.values()):
            raise ValueError("Frozen parent component identity differs")
        expected_scaffold = set(scaffold) & before.keys()
        if not expected_scaffold <= parent.keys():
            raise ValueError("Restored scaffold lacks exact frozen parent correspondence")
        if any(parent[n]["xyz"] != original[n]["xyz"] for n in expected_scaffold if n in original):
            raise ValueError("Frozen parent scaffold differs from the fresh canonical input")
        if any(after[n]["xyz"] != parent[n]["xyz"] for n in expected_scaffold):
            raise ValueError("Restored scaffold coordinates differ from frozen parent")
        names = ["C1'", *fragment]
        maximum = max((abs(dist(before[a]["xyz"], before[b]["xyz"])
                            - dist(after[a]["xyz"], after[b]["xyz"]))
                       for i, a in enumerate(names) for b in names[i+1:]), default=0.)
        if maximum > FRAGMENT_DISTANCE_TOLERANCE:
            raise ValueError("Restored base fragment geometry changed beyond PDB rounding")
        ordered = [*graph["frame_atoms"], graph["attachment_atom"]]
        volumes = [_volume([atoms[name]["xyz"] for name in ordered]) for atoms in (before, after)]
        if min(abs(v) for v in volumes) < .01 or volumes[0] * volumes[1] <= 0:
            raise ValueError("Restored glycosidic attachment orientation changed or is degenerate")
        results.append({"site": action.site, "component": action.after, "status": status,
                        "fragment_transport_tested": True, "fragment_atoms": list(fragment),
                        "scaffold_atoms": sorted(expected_scaffold),
                        "dictionary_heavy_atoms_absent_from_coot": sorted(heavy.keys() - before.keys()),
                        "attachment_orientation_preserved": True,
                        "max_fragment_distance_change": maximum,
                        "scaffold_matches_frozen_parent": True})
    fallbacks = [r["site"] for r in results if r["status"] == "RAW_SITE_RETAINED"]
    return {"status": "CONSTRUCTION_CONTROLS_PASS" if not fallbacks else "CONSTRUCTION_CONTROLS_PASS_WITH_NOTES",
            "sites": results, "raw_fallback_sites": fallbacks, "raw_composition_preserved": True,
            "atom_metadata_preserved": True, "unselected_raw_records_preserved": True,
            "unselected_input_coordinates_preserved": True, "noncoordinate_records_preserved": True,
            "scientific_geometry_qualification": "NOT_ASSESSED"}


def run_postmr_construction_controls(canonical_model: Path, dictionary_paths: Mapping[str, Path],
                                    output_directory: Path, *, coot_executable: Path | None = None,
                                    environment: Mapping[str, str] | None = None,
                                    coot_version: str | None = None, inspect_only: bool = False,
                                    atl_dictionary: Path | None = None,
                                    timeout_seconds: int = 600) -> dict:
    """Stage exact inputs and run one ordinary MTZ-free construction, if requested.

    The caller verifies the prior capsule bindings and discovers a validated
    Coot installation. Inspect-only stages a portable control plan and performs
    no native process. Failed execution is preserved as a failed report and
    raises, so a caller cannot mistake it for a completed audit.
    """
    from .postmr_restoration import source_graph_fragment

    codes = {row["component"] for row in ORDINARY_POSTMR_CONSTRUCTION_CONTROLS}
    if set(dictionary_paths) != codes:
        raise ValueError("Require exactly the explicit DP/PDU/5PC numerical dictionaries")
    if not isinstance(timeout_seconds, int) or isinstance(timeout_seconds, bool) or not 1 <= timeout_seconds <= 600:
        raise ValueError("Fresh Coot timeout must be from 1 to 600 seconds")
    output = Path(output_directory).absolute()
    if output.exists() or output.is_symlink():
        raise FileExistsError(output)
    if any(p.is_symlink() for p in output.parents):
        raise ValueError("Construction output cannot traverse a symlink")
    source_paths = {"canonical_model": Path(canonical_model),
                    **{code: Path(path) for code, path in dictionary_paths.items()}}
    if atl_dictionary is not None:
        source_paths["ATL"] = Path(atl_dictionary)
    snapshots = {name: path.read_bytes() for name, path in source_paths.items()}
    if any(not data for data in snapshots.values()):
        raise ValueError("Construction control source is empty")
    staged_model, removed = prepare_free_five_prime_model(snapshots["canonical_model"])
    # Validate graph availability before writing or attempting Coot. Numerical
    # parameters remain exactly those already qualified by the prior capsule.
    eligibility = {code: source_graph_fragment(Path(dictionary_paths[code]), code) for code in sorted(codes)}
    original_inventory = _pdb_inventory(canonical_model)
    for row in ORDINARY_POSTMR_CONSTRUCTION_CONTROLS:
        atoms = _atoms(original_inventory, row["site"])
        if any(a["code"] != row["parent"] for a in atoms.values()):
            raise ValueError("Fresh construction control is not in its declared canonical parent context")
    output.mkdir(parents=True)
    input_directory = output / "inputs"
    input_directory.mkdir()
    model = input_directory / "canonical_free_5oh.pdb"
    model.write_bytes(staged_model)
    dictionaries = {}
    for code in sorted(codes):
        path = input_directory / (code + ".cif")
        path.write_bytes(snapshots[code])
        dictionaries[code] = path
    atl = {"component": "ATL", "scope": "PUBLIC_GRAPH_ELIGIBILITY_ONLY", "coot_execution": "NOT_RUN",
           "restoration_eligibility": "NOT_ASSESSED",
           "reason": "No qualified numerical ATL dictionary is supplied for fresh Coot construction."}
    if atl_dictionary is not None:
        path = input_directory / "ATL.cif"
        path.write_bytes(snapshots["ATL"])
        atl["source"] = _reference(path, output)
        try:
            atl["graph_plan"] = source_graph_fragment(path, "ATL")
        except ValueError as exc:
            atl.update(restoration_eligibility="RAW_SITE_RETAINED", reason=str(exc),
                       notes=["ATL's source graph is retained; unsupported source classification or sugar topology is not rebuilt as DNA."])
        else:
            atl["restoration_eligibility"] = "GRAPH_FRAGMENT_ELIGIBLE"
    actions = tuple(MutationAction(row["site"], row["parent"], row["component"],
                                 "coot-parent-overlap", parent_code=row["parent"])
                    for row in ORDINARY_POSTMR_CONSTRUCTION_CONTROLS)
    report = {"policy_id": POLICY_ID, "status": "INSPECT_ONLY" if inspect_only else "PREPARED",
              "analysis_completed": False, "ordinary_construction_api": "nasolve.postmr.construct_postmr_model",
              "controls": [asdict(a) for a in actions], "source_graph_eligibility": eligibility,
              "expected_restoration_context": {row["site"]: {
                  "dictionary_scaffold_atoms_absent_from_parent": sorted(
                      set(eligibility[row["component"]]["scaffold_atoms"])
                      - _atoms(original_inventory, row["site"]).keys()),
                  "unmatched_raw_scaffold_policy": "RAW_SITE_RETAINED",
                  "actual_coot_composition": "NOT_YET_OBSERVED"}
                  for row in ORDINARY_POSTMR_CONSTRUCTION_CONTROLS},
              "input_model": _reference(model, output),
              "dictionaries": {code: _reference(path, output) for code, path in dictionaries.items()},
              "canonical_source_sha256": sha256(snapshots["canonical_model"]).hexdigest(),
              "five_prime_phosphate_atoms_removed": removed, "atl_control": atl,
              "coot": {"execution": "NOT_RUN", "version": coot_version, "timeout_seconds": timeout_seconds},
              "mr_execution": "NOT_RUN", "mtz_used": False, "readyset_execution": "NOT_RUN",
              "phenix_execution": "NOT_RUN", "optimization": "NOT_RUN", "refinement": "NOT_RUN",
              "user_cif_review_required": False, "scientific_geometry_qualification": "NOT_ASSESSED"}
    _json(output / "construction_plan.json", report)
    try:
        if not inspect_only:
            if coot_executable is None:
                raise ValueError("A validated Coot executable is required for fresh construction")
            from .postmr import construct_postmr_model
            report["coot"]["execution"] = "RUNNING"
            result = construct_postmr_model(model, actions, dictionaries, output / "model" / "constructed_model.pdb",
                coot_executable=Path(coot_executable), environment=environment,
                timeout_seconds=timeout_seconds)
            report["coot"]["execution"] = "COMPLETED"
            if result.get("raw_model") is None:
                raise ValueError("Fresh ordinary construction did not retain raw Coot evidence")
            report["audit"] = audit_postmr_construction(model, result["raw_model"], result["model"],
                actions, dictionaries, result["parent_models"], result["coordinate_restoration"])
            report["coordinate_restoration"] = result["coordinate_restoration"]
            report["outputs"] = {key: _reference(result[key], output) for key in ("model", "raw_model", "geometry_model", "coot_log")
                                 if result.get(key) is not None}
            report["parents"] = {site: _reference(path, output) for site, path in result["parent_models"].items()}
            report.update(status=report["audit"]["status"], analysis_completed=True)
        if not _preserved(source_paths, snapshots):
            raise ValueError("Construction control source changed during execution")
        report["source_inputs_preserved"] = True
    except Exception as exc:
        report.update(status="FAILED", error=str(exc), analysis_completed=False)
        if report["coot"]["execution"] == "RUNNING":
            report["coot"]["execution"] = "FAILED"
        report["source_inputs_preserved"] = _preserved(source_paths, snapshots)
        _json(output / "construction_report.json", report)
        raise
    _json(output / "construction_report.json", report)
    return report
